-- Create missing tables without deleting existing data.
-- Changes to existing tables require a separate migration.
CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(100) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    CONSTRAINT users_username_nonempty CHECK (CHAR_LENGTH(TRIM(username)) > 0)
);

CREATE TABLE IF NOT EXISTS cards (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id BIGINT NOT NULL REFERENCES users(id),
    name VARCHAR(200) NOT NULL,
    description VARCHAR(10000) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'TODO',
    CONSTRAINT cards_owner_name UNIQUE (owner_id, name),
    CONSTRAINT cards_name_nonempty CHECK (CHAR_LENGTH(TRIM(name)) > 0),
    CONSTRAINT cards_status CHECK (status IN ('TODO', 'INPROGRESS', 'TOBEREVISED', 'DONE'))
);

CREATE TABLE IF NOT EXISTS card_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    card_id BIGINT NOT NULL REFERENCES cards(id),
    occurred_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    status VARCHAR(20) NOT NULL,
    CONSTRAINT card_history_status CHECK (status IN ('TODO', 'INPROGRESS', 'TOBEREVISED', 'DONE'))
);

CREATE INDEX IF NOT EXISTS idx_card_history_card_id ON card_history(card_id, id);
